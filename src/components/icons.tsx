/** Envuelve un ícono y le suma micro-animación: pop al entrar + realce al hover. */
function AnimatedIcon({
  className,
  children,
}: {
  className?: string;
  children: ReactNode;
}) {
  const ref = useRef<HTMLSpanElement>(null);

  useGSAP(
    () => {
      const el = ref.current;
      if (!el) return;
      if (getMotionPrefs().reduced) return; // estático

      // Oculto hasta entrar en pantalla; el pop se arma recién ahí (ver
      // onEnterView: un ScrollTrigger por ícono leía el layout al cargar).
      let stopPop = () => {};
      if (revealsEnabled()) {
        hideUntilEnter(el);
        let pop: gsap.core.Tween | null = null;
        const stopEnter = onEnterView(el, () => {
          pop = gsap.fromTo(
            el,
            { scale: 0.5, autoAlpha: 0 },
            { scale: 1, autoAlpha: 1, duration: 0.6, ease: "back.out(1.7)" }
          );
        });
        stopPop = () => {
          stopEnter();
          pop?.kill();
        };
      }

      if (!allowHeavy()) return stopPop; // hover solo en desktop
      const enter = () =>
        gsap.to(el, {
          scale: 1.15,
          rotate: 6,
          duration: 0.3,
          ease: "power2.out",
          overwrite: "auto",
        });
      const leave = () =>
        gsap.to(el, {
          scale: 1,
          rotate: 0,
          duration: 0.45,
          ease: "power2.out",
          overwrite: "auto",
        });
      el.addEventListener("pointerenter", enter);
      el.addEventListener("pointerleave", leave);
      return () => {
        stopPop();
        el.removeEventListener("pointerenter", enter);
        el.removeEventListener("pointerleave", leave);
      };
    },
    { scope: ref }
  );

  return (
    <span
      ref={ref}
      className={cn("inline-flex items-center justify-center", className)}
    >
      {children}
    </span>
  );
}

export function Icon({ name, className }: { name: string; className?: string }) {
  return (
    <AnimatedIcon className={className}>
      <svg
        viewBox="0 0 24 24"
        width="100%"
        height="100%"
        fill="currentColor"
        aria-hidden="true"
      >
        {ICON_PATHS[name] ?? ICON_PATHS.sparkle}
      </svg>
    </AnimatedIcon>
  );
}
